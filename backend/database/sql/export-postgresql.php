$schema[] = '-- psql -d virtual_company -f 01_schema.sql';
$schema[] = 'BEGIN;';
$schema[] = '';

$foreignKeys = [];
$indexes = [];

foreach ($tables as $table) {
    $columns = $db->query('PRAGMA table_info('.$db->quote($table).')')->fetchAll(PDO::FETCH_ASSOC);
    $lines = [];
    $pk = [];
    foreach ($columns as $column) {
        $name = $column['name'];
        $type = mapType($column['type'], $table, $name, $jsonColumns);
        $line = '    '.$name.' '.$type;
        if ((int) $column['pk'] === 1 && count(array_filter($columns, fn ($c) => (int) $c['pk'] > 0)) === 1 && $type === 'bigint') {
            $line .= ' GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY';
        } elseif ((int) $column['pk'] > 0) {
            $pk[] = $name;
        }
        if ((int) $column['notnull'] === 1 && ! str_contains($line, 'PRIMARY KEY')) {
            $line .= ' NOT NULL';
        }
        if ($column['dflt_value'] !== null && ! str_contains($line, 'PRIMARY KEY')) {
            $line .= ' DEFAULT '.mapDefault((string) $column['dflt_value'], $type);
        }
        $lines[] = $line;
    }
    if ($pk !== []) {
        $lines[] = '    PRIMARY KEY ('.implode(', ', $pk).')';
    }
    $schema[] = 'CREATE TABLE '.$table.' (';
    $schema[] = implode(",\n", $lines);
    $schema[] = ');';
    $schema[] = '';

    foreach ($db->query('PRAGMA foreign_key_list('.$db->quote($table).')')->fetchAll(PDO::FETCH_ASSOC) as $fk) {
        $action = strtoupper((string) $fk['on_delete']);
        $action = $action === 'SET NULL' ? 'SET NULL' : ($action === 'CASCADE' ? 'CASCADE' : 'NO ACTION');
        $foreignKeys[] = sprintf(
            'ALTER TABLE %s ADD CONSTRAINT %s_%s_fk FOREIGN KEY (%s) REFERENCES %s (%s) ON DELETE %s;',
            $table,
            $table,
            $fk['from'],
            $fk['from'],
            $fk['table'],
            $fk['to'],
            $action,
        );
    }
}

foreach ($db->query("SELECT sql FROM sqlite_master WHERE type = 'index' AND sql IS NOT NULL") as $row) {
    $sql = (string) $row['sql'];
    $sql = preg_replace('/^CREATE UNIQUE INDEX/i', 'CREATE UNIQUE INDEX', $sql) ?? $sql;
    $sql = preg_replace('/^CREATE INDEX/i', 'CREATE INDEX', $sql) ?? $sql;
    $indexes[] = rtrim($sql, ';').';';
}

$schema[] = implode("\n", $foreignKeys);
$schema[] = '';
$schema[] = implode("\n", $indexes);
$schema[] = '';
$schema[] = 'COMMIT;';
$schema[] = '';

file_put_contents($outDir.'/01_schema.sql', implode("\n", $schema));


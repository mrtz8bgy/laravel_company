function mapType(string $raw, string $table, string $column, array $jsonColumns): string
{
    $type = strtolower(trim($raw));
    if (in_array($column, $jsonColumns[$table] ?? [], true)) {
        return 'jsonb';
    }
    if (str_contains($type, 'tinyint(1)')) {
        return 'boolean';
    }
    if (str_starts_with($type, 'varchar') || $type === 'varchar') {
        return 'varchar(255)';
    }
    if ($type === 'text') {
        return 'text';
    }
    if ($type === 'date') {
        return 'date';
    }
    if ($type === 'time') {
        return 'time';
    }
    if ($type === 'datetime' || str_contains($type, 'timestamp')) {
        return 'timestamp';
    }
    if (str_contains($type, 'int')) {
        return 'bigint';
    }

    return 'text';
}

function mapDefault(string $default, string $type): string
{
    $default = trim($default);
    if (preg_match("/^'(.*)'$/s", $default, $match)) {
        $default = str_replace("''", "'", $match[1]);
    }
    $default = trim($default, "()");
    if (strtoupper($default) === 'CURRENT_TIMESTAMP') {
        return 'CURRENT_TIMESTAMP';
    }
    if ($type === 'boolean') {
        return in_array($default, ['1', 'true'], true) ? 'true' : 'false';
    }
    if ($type === 'bigint') {
        return (string) (int) $default;
    }
    if ($type === 'time') {
        return "'".str_replace("'", "''", $default)."'";
    }

    return "'".str_replace("'", "''", $default)."'";
}

function columnType(array $columns, string $name): string
{
    foreach ($columns as $column) {
        if ($column['name'] === $name) {
            return strtolower((string) $column['type']);
        }
    }

    return 'text';
}

function literal(mixed $value, string $sqliteType, bool $json): string
{
    if ($value === null) {
        return 'NULL';
    }
    if (str_contains($sqliteType, 'tinyint(1)')) {
        return ((string) $value === '1' || $value === 1 || $value === true) ? 'true' : 'false';
    }
    if (is_int($value) || (is_string($value) && preg_match('/^-?\d+$/', $value) && str_contains($sqliteType, 'int') && ! str_contains($sqliteType, 'tinyint(1)'))) {
        return (string) $value;
    }
    $text = (string) $value;
    if ($json) {
        return "'".str_replace("'", "''", $text)."'::jsonb";
    }

    return "'".str_replace("'", "''", $text)."'";
}

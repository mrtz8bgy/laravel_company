    if (in_array($table, $skipData, true)) {
        continue;
    }
    $columns = $db->query('PRAGMA table_info('.$db->quote($table).')')->fetchAll(PDO::FETCH_ASSOC);
    $names = array_column($columns, 'name');
    $rows = $db->query('SELECT * FROM '.$table)->fetchAll(PDO::FETCH_ASSOC);
    if ($rows === []) {
        continue;
    }
    $seed[] = '-- '.$table;
    foreach (array_chunk($rows, 50) as $chunk) {
        $seed[] = 'INSERT INTO '.$table.' ('.implode(', ', $names).') VALUES';
        $values = [];
        foreach ($chunk as $row) {
            $cells = [];
            foreach ($names as $name) {
                $cells[] = literal($row[$name], columnType($columns, $name), in_array($name, $jsonColumns[$table] ?? [], true));
            }
            $values[] = '    ('.implode(', ', $cells).')';
        }
        $seed[] = implode(",\n", $values).';';
        $seed[] = '';
    }
    $hasId = in_array('id', $names, true);
    if ($hasId) {
        $seed[] = "SELECT setval(pg_get_serial_sequence('{$table}', 'id'), COALESCE((SELECT MAX(id) FROM {$table}), 1), true);";
        $seed[] = '';
    }
}

$seed[] = 'COMMIT;';
